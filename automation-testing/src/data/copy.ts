export type Locale = "vi" | "en";

const DICTS: Record<Locale, Record<CopyKey, string>> = { vi, en };

/**
 * One UI string, with `{name}` placeholders filled. Numbers are formatted the way the game formats them
 * (../client/src/i18n/index.ts → formatNumber: vi-VN / en-GB), so "0,8" in vi and "0.8" in en.
 */
export function t(key: CopyKey, params: Record<string, string | number> = {}, locale: Locale = "vi"): string {
  return DICTS[locale][key].replace(/\{(\w+)\}/g, (whole, name: string) => {
    const value = params[name];
    if (value === undefined) return whole;
    return typeof value === "number" ? new Intl.NumberFormat(locale === "vi" ? "vi-VN" : "en-GB").format(value) : value;
  });
}

/** Regex-safe version of a copy string, for name matchers that need ^…$ or a prefix. */
export function escapeRe(text: string): string {
  return text.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}
